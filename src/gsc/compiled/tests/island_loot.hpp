	std::vector<std::uint8_t> island_loot_source(std::size_t index)
	{
		static_assert(island_loot_cache_hex.size() == 4832 * 2);
		static_assert(island_loot_pickups_hex.size() == 29808 * 2);
		const auto hex = index == 0 ? island_loot_cache_hex : island_loot_pickups_hex;
		std::vector<std::uint8_t> result;
		result.reserve(hex.size() / 2);
		const auto digit = [](char value)
		{
			return value <= '9' ? value - '0' : value - 'a' + 10;
		};
		for (std::size_t i = 0; i < hex.size(); i += 2)
			result.push_back(static_cast<std::uint8_t>(
				16 * digit(hex[i]) + digit(hex[i + 1])));
		return result;
	}

	std::vector<std::uint8_t> island_loot_expected(std::size_t index)
	{
		auto result = island_loot_source(index);
		if (index == 0)
		{
			result[2221] = 0xEF;
			result[3962] = 0xF0;
		}
		else
		{
			result[4162] = 0x0E;
			result[4576] = 0xD3;
			result[15632] = 0xD9;
			result[15692] = 0xAE;
			result[28864] = 0xD4;
		}
		return result;
	}

	void island_loot_translation_checks()
	{
		namespace abi = gsc::island_loot_native_abi;
		for (std::size_t index = 0; index < abi::source_profiles.size(); ++index)
		{
			const auto& profile = abi::source_profiles[index];
			const auto source = island_loot_source(index);
			const auto reject = [](std::string_view name, std::vector<std::uint8_t> code)
			{
				const auto before = code;
				Check(!abi::translate_private_compiler_copy(name, code) && code == before,
					"loot ABI accepted or partially modified an unverified input");
			};
			Check(abi::fingerprint(source) == profile.source_fingerprint,
				"loot ABI fixture is not the installed converted profile");
			reject("scripts/mp/gametypes/br.gsc", source);
			reject("1805", source);
			reject(abi::source_profiles[1 - index].name, source);
			reject(profile.name, {});
			auto short_code = source;
			short_code.pop_back();
			reject(profile.name, short_code);
			auto long_code = source;
			long_code.push_back(0);
			reject(profile.name, long_code);
			for (const auto at : { std::size_t{ 0 }, source.size() - 1 })
			{
				auto changed = source;
				changed[at] ^= 1;
				reject(profile.name, changed);
			}
			for (const auto& site : profile.calls)
			{
				for (std::size_t field = 0; field < 3; ++field)
				{
					auto changed = source;
					changed[site.offset + field] ^= 1;
					reject(profile.name, changed);
				}
			}

			auto translated = source;
			Check(abi::translate_private_compiler_copy(profile.name, translated),
				"loot ABI rejected the genuine installed module");
			Check(translated == island_loot_expected(index),
				"loot ABI changed an opcode, argument count, or unrelated byte");
			Check(abi::fingerprint(translated) == profile.replay_fingerprint,
				"loot ABI output differs from the verified native calls");
			if (index == 1)
			{
				Check(translated[28666] == 0x1D && translated[28667] == 0x34 && translated[28668] == 0x04,
					"loot ABI replaced the total-capacity extension with remaining capacity");
			}
			reject(profile.name, translated);
		}
	}

	std::uint8_t* island_loot_linked_code{};
	bool island_loot_relocate{};

	void island_loot_native_link(void*, gsc::ScriptFile* script)
	{
		island_loot_linked_code = script->bytecode_;
		linked_input.assign(script->bytecode_, script->bytecode_ + script->bytecode_len_);
		if (island_loot_relocate)
			script->bytecode_[1] = 0x5A;
	}

