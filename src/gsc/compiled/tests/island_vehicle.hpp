	void island_vehicle_stack_checks(std::span<const std::uint8_t> code)
	{
		// This small interpreter follows Replay's actual VM handlers, independently
		// of the translation implementation: 0x58 releases/pops, 0x16 pushes the
		// next byte as an integer, and 0x5C pushes integer zero.
		const auto execute = [](std::span<const std::uint8_t> instructions,
			std::vector<int>& stack, std::vector<int>& released)
		{
			for (std::size_t pc = 0; pc < instructions.size(); ++pc)
			{
				switch (instructions[pc])
				{
				case 0x58:
					Check(!stack.empty(), "vehicle compatibility statement underflowed the VM stack");
					released.push_back(stack.back());
					stack.pop_back();
					break;
				case 0x16:
					Check(pc + 1 < instructions.size(), "vehicle compatibility integer operand is truncated");
					stack.push_back(instructions[++pc]);
					break;
				case 0x5C:
					stack.push_back(0);
					break;
				default:
					Check(false, "vehicle compatibility statement invoked an unsupported opcode");
				}
			}
		};
		std::vector<int> horn_stack{ 0x5151, 0xA1, 0xE1 };
		std::vector<int> horn_released;
		execute(code.subspan(3322, 4), horn_stack, horn_released);
		Check(horn_stack == std::vector<int>{ 0x5151 } &&
			horn_released == std::vector<int>{ 0xE1, 0xA1, 0 },
			"optional horn customization did not release both operands and its discarded result");
		std::vector<int> policy_stack{ 0x5151, 0xE1 };
		std::vector<int> policy_released;
		execute(code.subspan(10177, 3), policy_stack, policy_released);
		Check(policy_stack == std::vector<int>{ 0x5151, 0 } &&
			policy_released == std::vector<int>{ 0xE1 },
			"keyboard exit policy did not replace the receiver with integer false");
		Check(code[10180] == 0x01 && code[10181] == 0x05,
			"keyboard exit policy changed the original local assignment");
	}

