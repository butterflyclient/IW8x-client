	std::vector<std::uint8_t> island_vehicle_mp_source()
	{
		static_assert(island_vehicle_mp_source_hex.size() == 2 * 2687);
		std::vector<std::uint8_t> result;
		result.reserve(island_vehicle_mp_source_hex.size() / 2);
		const auto digit = [](char value)
		{
			return value <= '9' ? value - '0' : value - 'a' + 10;
		};
		for (std::size_t i = 0; i < island_vehicle_mp_source_hex.size(); i += 2)
		{
			result.push_back(static_cast<std::uint8_t>(
				16 * digit(island_vehicle_mp_source_hex[i]) + digit(island_vehicle_mp_source_hex[i + 1])));
		}
		return result;
	}

	std::vector<std::uint8_t> island_vehicle_mp_expected()
	{
		auto result = island_vehicle_mp_source();
		result[1782] = 0x63;
		return result;
	}

	void island_vehicle_mp_abi_checks()
	{
		namespace abi = gsc::island_vehicle_native_abi;
		const auto* selected = abi::find_profile("2441");
		Check(selected && selected->length == 2687 && selected->calls.size() == 1 && selected->rewrites.empty(),
			"MP vehicle profile is missing or has unexpected translations");
		Check(!abi::find_profile("2269") && !abi::find_profile("scripts/mp/vehicles/vehicle_occupancy_mp.gsc"),
			"MP vehicle profile admitted an unverified module name");
		const auto source = island_vehicle_mp_source();
		Check(abi::fingerprint(source) == 0xFBD9694D41C8026BULL,
			"MP vehicle fixture is not the complete installed module");
		const auto reject = [](std::string_view module, std::vector<std::uint8_t> code)
		{
			const auto original = code;
			Check(!abi::translate_private_compiler_copy(module, code) && code == original,
				"MP vehicle translation accepted or modified an unverified input");
		};
		reject("2273", source);
		reject("2269", source);
		reject("2441", {});
		auto truncated = source;
		truncated.pop_back();
		reject("2441", truncated);
		auto extended = source;
		extended.push_back(0);
		reject("2441", extended);
		for (const auto offset : { std::size_t{ 0 }, std::size_t{ 1752 }, std::size_t{ 1781 },
			std::size_t{ 1782 }, std::size_t{ 1783 }, source.size() - 1 })
		{
			auto changed = source;
			changed[offset] ^= 1;
			reject("2441", changed);
		}
		auto translated = source;
		Check(abi::translate_private_compiler_copy("2441", translated),
			"MP vehicle translation rejected the installed module");
		Check(translated == island_vehicle_mp_expected() &&
			abi::fingerprint(translated) == 0xC7CB0F183793A7F2ULL,
			"MP vehicle translation changed anything beyond the weapon comparison operand");
		Check(translated[1751] == 0x1E && translated[1752] == 0x64 && translated[1753] == 0x03,
			"MP vehicle translation changed the already-converted null-weapon check");
		reject("2441", translated);
	}

	void island_vehicle_abi_checks()
	{
		namespace abi = gsc::island_vehicle_native_abi;
		const auto source = island_vehicle_source();
		const auto reject = [](std::string_view name, std::vector<std::uint8_t> code)
		{
			const auto before = code;
			Check(!abi::translate_private_compiler_copy(name, code) && code == before,
				"vehicle ABI accepted or partially modified an unverified input");
		};
		Check(abi::fingerprint(source) == 0x64B5A38DFD635FDFULL,
			"vehicle ABI fixture is not the installed converted occupancy profile");
		reject("2275", source);
		reject("scripts/cp_mp/vehicles/vehicle_occupancy.gsc", source);
		reject(abi::source_module, {});
		auto short_code = source;
		short_code.pop_back();
		reject(abi::source_module, short_code);
		auto long_code = source;
		long_code.push_back(0);
		reject(abi::source_module, long_code);
		for (const auto at : { std::size_t{ 0 }, source.size() - 1 })
		{
			auto changed = source;
			changed[at] ^= 1;
			reject(abi::source_module, changed);
		}
		for (const auto& site : abi::calls)
		{
			for (std::size_t field = 0; field < 3; ++field)
			{
				auto changed = source;
				changed[site.offset + field] ^= 1;
				reject(abi::source_module, changed);
			}
		}
		for (const auto& site : abi::rewrites)
		{
			for (std::size_t field = 0; field < 3; ++field)
			{
				auto changed = source;
				changed[site.offset + field] ^= 1;
				reject(abi::source_module, changed);
			}
		}
		auto translated = source;
		Check(abi::translate_private_compiler_copy(abi::source_module, translated),
			"vehicle ABI rejected the genuine installed occupancy module");
		Check(translated == island_vehicle_expected(),
			"vehicle ABI changed an argument count, branch, field operand or unrelated byte");
		Check(abi::fingerprint(translated) == 0x486C749524D304F3ULL,
			"vehicle ABI output differs from the verified Replay-compatible profile");
		island_vehicle_stack_checks(translated);
		reject(abi::source_module, translated);
		island_vehicle_mp_abi_checks();
	}

	std::uint8_t* island_vehicle_linked_code{};
	bool island_vehicle_relocate{};

	void island_vehicle_native_link(void*, gsc::ScriptFile* script)
	{
		island_vehicle_linked_code = script->bytecode_;
		linked_input.assign(script->bytecode_, script->bytecode_ + script->bytecode_len_);
		if (island_vehicle_relocate)
		{
			script->bytecode_[1] = 0x5A;
		}
	}

	void island_vehicle_link_checks()
	{
		using namespace game::addresses::gsc;
		namespace abi = gsc::island_vehicle_native_abi;
		const auto source = island_vehicle_source();
		const auto expected = island_vehicle_expected();
		const auto native_size = (source.size() + 7) & ~std::size_t{ 7 };
		island_resident.assign(native_size + gsc::probe_code_capacity, 0);
		std::copy(source.begin(), source.end(), island_resident.begin());
		gsc::ResetCompactCode();
		gsc::probe_code_begin = island_resident.data() + native_size;
		gsc::get_script_program_range = IslandProgramRange;
		gsc::original_link_file = island_vehicle_native_link;
		Check(VirtualAlloc(game::at(kServerContextRva & ~std::uintptr_t(0xFFF)), 0xD000,
			MEM_COMMIT, PAGE_READWRITE) != nullptr, "commit vehicle linker context");
		ClearContext();
		auto* server = game::at(kServerContextRva);
		auto** map = game::at<const char*>(0x5cc7538);
		*map = "mp_sm_island_1";
		gsc::canonical_delta = 1;
		gsc::link_epoch = 70;
		gsc::installed.store(true);
		Context<std::uint8_t>(kLoadingScriptsOffset) = 1;
		char packed = 'S';
		gsc::ScriptFile script{};
		script.name_ = abi::source_module.data();
		script.buffer_ = &packed;
		script.compressed_len_ = 1;
		script.len_ = 1;
		script.bytecode_ = island_resident.data();
		script.bytecode_len_ = static_cast<int>(source.size());
		const auto excluded = [&](void* context)
		{
			gsc::LinkScriptFile(context, &script);
			Check(linked_input == source && island_vehicle_linked_code == script.bytecode_ &&
				gsc::island_vehicle_rebound_code.empty(),
				"vehicle ABI escaped the Island server load gate");
		};
		gameplay_fixture = false;
		excluded(server);
		gameplay_fixture = true;
		std::array<std::uint8_t, 16> client_context{};
		excluded(client_context.data());
		*map = "mp_shipment";
		excluded(server);
		*map = "mp_sm_island_1";
		gsc::canonical_delta = 0;
		excluded(server);
		gsc::canonical_delta = 1;
		gsc::link_epoch = 0;
		excluded(server);
		gsc::link_epoch = 70;
		Context<std::uint8_t>(kLoadingScriptsOffset) = 0;
		excluded(server);
		Context<std::uint8_t>(kLoadingScriptsOffset) = 1;
		Context<std::uint32_t>(kVMFrameCountOffset) = 1;
		excluded(server);
		Context<std::uint32_t>(kVMFrameCountOffset) = 0;

		script.name_ = "2275";
		gsc::LinkScriptFile(server, &script);
		Check(linked_input == source && gsc::island_vehicle_rebound_code.empty(),
			"vehicle ABI translated another module inside an Island load");
		gsc::ResetCompactCode();
		gsc::probe_code_begin = island_resident.data() + native_size;
		script.name_ = abi::source_module.data();
		island_vehicle_relocate = true;
		gsc::LinkScriptFile(server, &script);
		Check(linked_input == expected && island_vehicle_linked_code != script.bytecode_ &&
			gsc::island_vehicle_rebound_code.size() == 1,
			"vehicle ABI did not translate the selected private compiler copy");
		Check(std::equal(source.begin(), source.end(), script.bytecode_) &&
			script.buffer_ == &packed && packed == 'S' && script.bytecode_len_ == static_cast<int>(source.size()),
			"vehicle ABI modified the registered ScriptFile or native payload");
		const auto first_copy = island_vehicle_linked_code;
		gsc::LinkScriptFile(server, &script);
		auto relocated = expected;
		relocated[1] = 0x5A;
		Check(island_vehicle_linked_code == first_copy && linked_input == relocated &&
			gsc::island_vehicle_rebound_code.size() == 1,
			"repeat link retranslated relocated vehicle bytecode");
		island_vehicle_relocate = false;
		gsc::link_epoch = 71;
		gsc::LinkScriptFile(server, &script);
		Check(linked_input == expected && gsc::island_vehicle_rebound_code.size() == 1,
			"new load retained stale vehicle translation state");
		gsc::ResetCompactCode();
		Check(gsc::island_vehicle_rebound_code.empty(), "zone reset retained vehicle translation state");

		// Load the second profile through the same private-copy path after reset.
		// Its one-argument null check must remain registered exactly as installed.
		const auto mp_source = island_vehicle_mp_source();
		const auto mp_expected = island_vehicle_mp_expected();
		std::copy(mp_source.begin(), mp_source.end(), island_resident.begin());
		gsc::probe_code_begin = island_resident.data() + native_size;
		script.name_ = "2441";
		script.bytecode_len_ = static_cast<int>(mp_source.size());
		gsc::link_epoch = 72;
		island_vehicle_relocate = true;
		gsc::LinkScriptFile(server, &script);
		Check(linked_input == mp_expected && island_vehicle_linked_code != script.bytecode_ &&
			gsc::island_vehicle_rebound_code.size() == 1 &&
			std::equal(mp_source.begin(), mp_source.end(), script.bytecode_),
			"MP vehicle profile did not preserve its registered module while translating a private copy");
		const auto mp_copy = island_vehicle_linked_code;
		gsc::LinkScriptFile(server, &script);
		auto mp_relocated = mp_expected;
		mp_relocated[1] = 0x5A;
		Check(island_vehicle_linked_code == mp_copy && linked_input == mp_relocated &&
			gsc::island_vehicle_rebound_code.size() == 1,
			"repeat link retranslated the relocated MP vehicle profile");
		island_vehicle_relocate = false;
		gsc::ResetCompactCode();
		Check(gsc::island_vehicle_rebound_code.empty(), "zone reset retained the MP vehicle profile");
		gsc::installed.store(false);
		gsc::canonical_delta = 0;
		gsc::link_epoch = 0;
		*map = nullptr;
		ClearContext();
		gsc::get_script_program_range = FakeProgramRange;
		std::cout << "Island vehicle ABI calls, stack effects, fingerprints, private copies, reload and scope checks passed\n";
	}
