	std::vector<std::uint8_t> island_killstreak_source()
	{
		static_assert(island_killstreak_source_hex.size() == 2 * gsc::island_killstreak_native_abi::source_length);
		std::vector<std::uint8_t> result;
		result.reserve(island_killstreak_source_hex.size() / 2);
		const auto digit = [](char value)
		{
			return value <= '9' ? value - '0' : value - 'a' + 10;
		};
		for (std::size_t i = 0; i < island_killstreak_source_hex.size(); i += 2)
		{
			result.push_back(static_cast<std::uint8_t>(
				16 * digit(island_killstreak_source_hex[i]) + digit(island_killstreak_source_hex[i + 1])));
		}
		return result;
	}

	std::vector<std::uint8_t> island_killstreak_expected()
	{
		auto result = island_killstreak_source();
		// Independently extracted installed call sites and native registry matches.
		result[1647] = 0x2B;
		result[5136] = 0x2A;
		result[5158] = 0x2C;
		return result;
	}

	void island_killstreak_translation_checks()
	{
		namespace abi = gsc::island_killstreak_native_abi;
		const auto source = island_killstreak_source();
		const auto reject = [](std::string_view name, std::vector<std::uint8_t> code)
		{
			const auto before = code;
			Check(!abi::translate_private_compiler_copy(name, code) && code == before,
				"killstreak ABI accepted or partially modified an unverified input");
		};
		Check(abi::fingerprint(source) == 0xD794D364148C86B9ULL,
			"killstreak ABI fixture is not the installed converted profile");
		reject("2355", source);
		reject("scripts/mp/killstreaks/killstreaks.gsc", source);
		reject(abi::source_module, {});
		auto short_code = source;
		short_code.pop_back();
		reject(abi::source_module, short_code);
		auto long_code = source;
		long_code.push_back(0);
		reject(abi::source_module, long_code);
		for (const auto at : { std::size_t{ 0 }, source.size() - 1 })
		{
			auto changed = source;
			changed[at] ^= 1;
			reject(abi::source_module, changed);
		}
		for (const auto& site : abi::calls)
		{
			for (std::size_t field = 0; field < 3; ++field)
			{
				auto changed = source;
				changed[site.offset + field] ^= 1;
				reject(abi::source_module, changed);
			}
		}

		auto translated = source;
		Check(abi::translate_private_compiler_copy(abi::source_module, translated),
			"killstreak ABI rejected the genuine installed module");
		Check(translated == island_killstreak_expected(),
			"killstreak ABI changed an opcode, argument count, or unrelated byte");
		Check(abi::fingerprint(translated) == 0x9D09B63C4ED0FA5FULL,
			"killstreak ABI output differs from the verified native calls");
		reject(abi::source_module, translated);
	}

	std::uint8_t* island_killstreak_linked_code{};
	bool island_killstreak_relocate{};

	void island_killstreak_native_link(void*, gsc::ScriptFile* script)
	{
		island_killstreak_linked_code = script->bytecode_;
		linked_input.assign(script->bytecode_, script->bytecode_ + script->bytecode_len_);
		if (island_killstreak_relocate)
		{
			script->bytecode_[1] = 0x5A;
		}
	}

	void island_killstreak_link_checks()
	{
		using namespace game::addresses::gsc;
		namespace abi = gsc::island_killstreak_native_abi;
		const auto source = island_killstreak_source();
		const auto expected = island_killstreak_expected();
		const auto native_size = (source.size() + 7) & ~std::size_t{ 7 };
		island_resident.assign(native_size + gsc::probe_code_capacity, 0);
		std::copy(source.begin(), source.end(), island_resident.begin());
		gsc::ResetCompactCode();
		gsc::probe_code_begin = island_resident.data() + native_size;
		gsc::get_script_program_range = IslandProgramRange;
		gsc::original_link_file = island_killstreak_native_link;
		Check(VirtualAlloc(game::at(kServerContextRva & ~std::uintptr_t(0xFFF)), 0xD000,
			MEM_COMMIT, PAGE_READWRITE) != nullptr, "commit killstreak linker context");
		ClearContext();
		auto* server = game::at(kServerContextRva);
		auto** map = game::at<const char*>(0x5cc7538);
		*map = "mp_sm_island_1";
		gsc::canonical_delta = 1;
		gsc::link_epoch = 60;
		gsc::installed.store(true);
		Context<std::uint8_t>(kLoadingScriptsOffset) = 1;
		char packed = 'S';
		gsc::ScriptFile script{};
		script.name_ = abi::source_module.data();
		script.buffer_ = &packed;
		script.compressed_len_ = 1;
		script.len_ = 1;
		script.bytecode_ = island_resident.data();
		script.bytecode_len_ = static_cast<int>(source.size());
		const auto excluded = [&](void* context)
		{
			gsc::LinkScriptFile(context, &script);
			Check(linked_input == source && island_killstreak_linked_code == script.bytecode_ &&
				gsc::island_killstreak_rebound_code.empty(),
				"killstreak ABI escaped the Island server load gate");
		};

		gameplay_fixture = false;
		excluded(server);
		gameplay_fixture = true;
		std::array<std::uint8_t, 16> client_context{};
		excluded(client_context.data());
		*map = "mp_shipment";
		excluded(server);
		*map = "mp_sm_island_1";
		gsc::canonical_delta = 0;
		excluded(server);
		gsc::canonical_delta = 1;
		gsc::link_epoch = 0;
		excluded(server);
		gsc::link_epoch = 60;
		Context<std::uint8_t>(kLoadingScriptsOffset) = 0;
		excluded(server);
		Context<std::uint8_t>(kLoadingScriptsOffset) = 1;
		Context<std::uint32_t>(kVMFrameCountOffset) = 1;
		excluded(server);
		Context<std::uint32_t>(kVMFrameCountOffset) = 0;

		script.name_ = "2355";
		gsc::LinkScriptFile(server, &script);
		Check(linked_input == source && gsc::island_killstreak_rebound_code.empty(),
			"killstreak ABI translated another module inside an Island load");
		gsc::ResetCompactCode();
		gsc::probe_code_begin = island_resident.data() + native_size;
		script.name_ = abi::source_module.data();
		island_killstreak_relocate = true;
		gsc::LinkScriptFile(server, &script);
		Check(linked_input == expected && island_killstreak_linked_code != script.bytecode_ &&
			gsc::island_killstreak_rebound_code.size() == 1,
			"killstreak ABI did not translate the selected private compiler copy");
		Check(std::equal(source.begin(), source.end(), script.bytecode_) &&
			script.buffer_ == &packed && packed == 'S' && script.bytecode_len_ == static_cast<int>(source.size()),
			"killstreak ABI modified the registered ScriptFile or native payload");

		const auto first_copy = island_killstreak_linked_code;
		gsc::LinkScriptFile(server, &script);
		auto relocated = expected;
		relocated[1] = 0x5A;
		Check(island_killstreak_linked_code == first_copy && linked_input == relocated &&
			gsc::island_killstreak_rebound_code.size() == 1,
			"repeat link retranslated relocated killstreak bytecode");
		island_killstreak_relocate = false;
		gsc::link_epoch = 61;
		gsc::LinkScriptFile(server, &script);
		Check(linked_input == expected && gsc::island_killstreak_rebound_code.size() == 1,
			"new load retained stale killstreak translation state");
		gsc::ResetCompactCode();
		Check(gsc::island_killstreak_rebound_code.empty(), "zone reset retained killstreak translation state");

		gsc::installed.store(false);
		gsc::canonical_delta = 0;
		gsc::link_epoch = 0;
		*map = nullptr;
		ClearContext();
		gsc::get_script_program_range = FakeProgramRange;
		std::cout << "Island killstreak ABI owner, opcodes, fingerprints, private copies, reload and scope checks passed\n";
	}
