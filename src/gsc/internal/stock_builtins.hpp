	inline const stock_builtin* find_builtin(bool method, std::string_view name) noexcept
	{
		size_t first = 0, last = std::size(stock_builtins);
		while (first < last)
		{
			const auto middle = first + (last - first) / 2;
			const auto& item = stock_builtins[middle];
			if (item.method < method || (item.method == method && item.name < name))
				first = middle + 1;
			else
				last = middle;
		}
		if (first == std::size(stock_builtins)) return nullptr;
		const auto& item = stock_builtins[first];
		return item.method == method && item.name == name ? &item : nullptr;
	}
