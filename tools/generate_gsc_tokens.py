"""Generate the stock IW8 canonical identifier table (never runs at game startup)."""
import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "thirdparty/xensik-gsc/iw8_token.cpp"
OUTPUT = ROOT / "src/gsc/internal/stock_script_tokens.inc"
ROW = re.compile(r'^\s*\{\s*(0x[0-9A-Fa-f]+),\s*"([A-Za-z_][A-Za-z_0-9/-]*)"\s*\},', re.M)


def generate(source):
    names = {}
    for token, name in ROW.findall(source.decode("utf-8-sig")):
        # Match xensik's token_map_rev_.insert: first exact spelling wins.
        # Do not fold case here: e.g. aiSpread and aispread have distinct IDs.
        names.setdefault(name, int(token, 16))
    if not names:
        raise ValueError("no IW8 canonical identifiers found")
    lines = [
        "// Generated by tools/generate_gsc_tokens.py from xensik IW8 iw8_token.cpp.",
        "// Copyright 2026 xensik. GPL-3.0; see thirdparty/xensik-gsc/LICENSE.",
        "// MW 1.44 canonical identifiers, NOT builtin function/method IDs.",
        "// Includes module paths: retail far calls use their decimal token as the asset name.",
        "// Source SHA-256: " + hashlib.sha256(source).hexdigest(),
    ]
    lines.extend(f'    {{"{name}", 0x{token:X}}},' for name, token in sorted(names.items()))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(args.source.read_bytes())
    if args.check:
        if args.output.read_text(encoding="utf-8") != generated:
            raise SystemExit("stock script token table is out of date")
    else:
        args.output.write_text(generated, encoding="utf-8", newline="\n")
